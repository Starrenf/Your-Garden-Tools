import {readFileSync,writeFileSync} from 'node:fs';
const p='src/main.jsx';
let jsx=readFileSync(p,'utf8');
let css=readFileSync('src/styles.css','utf8');
const hero='Voor grasmaaiers, heggenscharen en andere tuin- en parkmachines. Duidelijke afspraken, deskundig advies en aandacht voor uw machine.';
const heroNew='Onderhoud, reparatie en service aan huis voor grasmaaiers, heggenscharen en andere tuin- en parkmachines. Op afspraak haalt Ludo uw machine bij u thuis op. Duidelijke afspraken en deskundig advies.';
if(jsx.includes(hero))jsx=jsx.replace(hero,heroNew);
else if(!jsx.includes(heroNew))throw Error('Hero tekst niet gevonden');
const card='<Service n="04" title="Advies & verkoop" text="Eerlijk advies over onderdelen, onderhoud en passende machines."/>';
const cardNew=card+'<Service n="05" title="Service aan huis" text="Geen mogelijkheid om de tuinmachine zelf te brengen? Ludo haalt deze op afspraak bij u thuis op. Neem contact op om de mogelijkheden en kosten te bespreken."/>';
if(jsx.includes(card))jsx=jsx.replace(card,cardNew);
else if(!jsx.includes('title="Service aan huis"'))throw Error('Servicecard niet gevonden');
const fourth='<div><b>04</b>Betrouwbaar advies</div>';
if(jsx.includes(fourth))jsx=jsx.replace(fourth,'<div><b>04</b>Ophaalservice aan huis</div>');
const contact='<div className="contactInfo"><span><small>Werkplaats</small>';
if(jsx.includes(contact))jsx=jsx.replace(contact,'<p className="serviceHomeNote">Service aan huis: op afspraak kunnen wij uw tuinmachine bij u thuis ophalen. Bel voor de mogelijkheden en tarieven.</p>'+contact);
if(!css.includes('.serviceHomeNote{'))css+='\n.public-view.page-diensten .cards{grid-template-columns:repeat(auto-fit,minmax(210px,1fr))}.serviceHomeNote{margin:22px 0;padding:18px 22px;background:#f0f7eb;border-radius:13px;color:#344f30;line-height:1.65;font-size:15px}\n';
writeFileSync(p,jsx,'utf8');
writeFileSync('src/styles.css',css,'utf8');
console.log('Service aan huis and collection by appointment added to public site.');
